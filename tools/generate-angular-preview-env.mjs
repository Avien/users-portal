#!/usr/bin/env node
// Generates apps/users-portal-angular/src/environments/environment.preview.ts
// immediately before the Angular "preview" build — this file is gitignored,
// NOT a committed constant. The backends these URLs point at (a Railway PR
// Environment, a React Vercel Preview deployment) are ephemeral — tied to a
// specific branch/PR and torn down when it closes; committing any of them as
// a permanent source file would leave every future Angular Preview build
// (VERCEL_ENV=preview keeps selecting this file) silently pointing at a dead
// backend/remote.
//
// Reuses VITE_ORDERS_API_URL / VITE_ORDERS_WS_URL / VITE_REACT_REMOTE_URL —
// the same Vercel env var naming convention React/Vue already use via
// import.meta.env for their own Preview deployments — rather than inventing
// Angular-specific variable names.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ordersApiUrl = process.env['VITE_ORDERS_API_URL']?.trim();
const ordersWsUrl = process.env['VITE_ORDERS_WS_URL']?.trim();
const reactRemoteUrl = process.env['VITE_REACT_REMOTE_URL']?.trim();

if (!ordersApiUrl || !ordersWsUrl || !reactRemoteUrl) {
  console.error(
    '[generate-angular-preview-env] Missing, empty, or whitespace-only VITE_ORDERS_API_URL, VITE_ORDERS_WS_URL, and/or VITE_REACT_REMOTE_URL.\n' +
      'Refusing to generate environment.preview.ts with a partial/default value —\n' +
      'that could silently point Preview HTTP/WS/the Hybrid MFE React remote at\n' +
      'mismatched backends. Set all three as Preview-scoped env vars on this\n' +
      'Vercel project before building.'
  );
  process.exit(1);
}

const outPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../apps/users-portal-angular/src/environments/environment.preview.ts'
);

const contents = `// AUTO-GENERATED by tools/generate-angular-preview-env.mjs — gitignored, do
// not commit or hand-edit. Regenerated on every Angular Preview build from
// the Preview-scoped Vercel env vars VITE_ORDERS_API_URL / VITE_ORDERS_WS_URL /
// VITE_REACT_REMOTE_URL. Not a permanent constant: whatever backends/remotes
// these URLs point at are expected to be ephemeral (e.g. a Railway PR
// Environment, a React Vercel Preview deployment).
export const environment = {
  ordersApiUrl: ${JSON.stringify(ordersApiUrl)},
  ordersWsUrl: ${JSON.stringify(ordersWsUrl)},
  reactRemoteUrl: ${JSON.stringify(reactRemoteUrl)},
  // Same same-origin fallback as production — this Preview deployment gets
  // its own bundled /api/business-agent Vercel Function.
  businessAgentEndpoint: undefined as string | undefined,
};
`;

writeFileSync(outPath, contents);
console.log(`[generate-angular-preview-env] wrote ${outPath}`);
console.log(`  ordersApiUrl   = ${ordersApiUrl}`);
console.log(`  ordersWsUrl    = ${ordersWsUrl}`);
console.log(`  reactRemoteUrl = ${reactRemoteUrl}`);
